NOTIFY_UUID = "0000fff4-0000-1000-8000-00805f9b34fb"

DEFAULT_DEVICE_NAME = "JTX-HC"

_HEAD = 0xBC
_TAIL = 0x55


def _clamp(value: int, low: int, high: int) -> int:
    return low if value < low else high if value > high else value


def _u16(value: int) -> tuple[int, int]:
    return value >> 8 & 0xFF, value & 0xFF


def power(on: bool) -> bytes:
    return bytes([_HEAD, 0x01, 0x01, 0x01 if on else 0x00, _TAIL])


def brightness(level: int) -> bytes:
    """Яркость 0..1000."""
    hi, lo = _u16(_clamp(int(level), 0, 1000))
    return bytes([_HEAD, 0x05, 0x06, hi, lo, 0, 0, 0, 0, _TAIL])


def hue_sat(hue: int, sat: int) -> bytes:
    """Оттенок в градусах 0..359 и насыщенность 0..1000 (0 — белый)."""
    hue_hi, hue_lo = _u16(int(hue) % 360)
    sat_hi, sat_lo = _u16(_clamp(int(sat), 0, 1000))
    return bytes([_HEAD, 0x04, 0x06, hue_hi, hue_lo, sat_hi, sat_lo, 0, 0, _TAIL])


def effect(effect_id: int) -> bytes:
    return bytes([_HEAD, 0x06, 0x02, 0x00, effect_id & 0xFF, _TAIL])


def effect_reversed(is_reversed: bool) -> bytes:
    return bytes([_HEAD, 0x07, 0x01, 0x01 if is_reversed else 0x00, _TAIL])


def effect_speed(speed: int) -> bytes:
    """Скорость эффекта 1..100."""
    return bytes([_HEAD, 0x08, 0x01, _clamp(int(speed), 1, 100), _TAIL])


