"""Команды BLE-контроллера ламп (JTX-HC, семейство MR Star / SymphonyLight).

Формат пакета: BC <команда> <длина данных> <данные…> 55.
Пакеты пишутся в характеристику FFF3 сервиса FFF0.

Питание, яркость и цвет проверены на железе. Остальное — по разбору официального
приложения в nukemberg/cheap-leds (PROTOCOL.md) и hirotasoshu/ha-findn-led-ble.

Команды 02 (порядок каналов) и 03 (число светодиодов) меняют постоянные настройки
контроллера и здесь намеренно не реализованы. Команды цвета для отдельных участков
в протоколе нет: цвет всегда один на весь контроллер.
"""

